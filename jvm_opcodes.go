func opcodeLength(opcode int, code []byte, pc int) int {
	if length, ok := opcodeLengths[opcode]; ok {
		return length
	}

	switch opcode {
	case 0xaa: // tableswitch
		alignedPC := (pc + 4) & ^3
		low := int32(binary.BigEndian.Uint32(code[alignedPC+4 : alignedPC+8]))
		high := int32(binary.BigEndian.Uint32(code[alignedPC+8 : alignedPC+12]))
		return (alignedPC - pc) + 12 + int(high-low+1)*4
	case 0xab: // lookupswitch
		alignedPC := (pc + 4) & ^3
		nPairs := int32(binary.BigEndian.Uint32(code[alignedPC+4 : alignedPC+8]))
		return (alignedPC - pc) + 8 + int(nPairs)*8
	case 0xc4: // wide
		subOpcode := int(code[pc+1])
		if subOpcode == 0x84 {
			return 6
		}
		return 4
	default:
		return 1
	}
}
